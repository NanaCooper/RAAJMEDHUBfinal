async function seed() {
  const commsRef = collection(db, 'procedure_commissions');

  console.log('Seeding procedure commissions for Takoradi...');
  let count = 0;
  for (const proc of takoradiCommissions) {
    try {
      await addDoc(commsRef, {
        procedureName: proc.procedureName,
        branch: 'Takoradi',
        priceGhs: proc.priceGhs,
        commissionGhs: proc.commissionGhs
      });
      count++;
    } catch (err) {
      console.error(`Failed to add ${proc.procedureName}`, err);
    }
  }
  
  console.log(`Successfully seeded ${count} commission records for Takoradi.`);
  process.exit(0);
}

